// Read-only regression: replay real saved packets through a delayed browser handoff.
// The synthetic response timing and one-frame preview envelope are test fixtures;
// robot state, terminal status, failure text and complete recordings are real data.
import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
const base=process.env.STUDIO_URL||'http://127.0.0.1:8790';
const completedId=process.env.STUDIO_COMPLETED_JOB,failedId=process.env.STUDIO_FAILED_JOB;
assert.ok(completedId&&failedId,'Set STUDIO_COMPLETED_JOB and STUDIO_FAILED_JOB to existing recorded jobs; no workers are launched.');
const evidence=process.env.STUDIO_EVIDENCE||path.join(os.homedir(),'research-data/g1-deploy-studio/evidence/replay-transition');
await mkdir(evidence,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/opt/google/chrome/chrome',headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1512,height:1100}}),errors=[],checks=[];
page.on('pageerror',error=>errors.push(error.message));
const get=async url=>{const response=await page.request.get(base+url);assert.equal(response.status(),200);return response.json();};
const ready=id=>page.waitForFunction(id=>window.__studio?.state.sessionId===id&&!window.__studio.state.loading&&document.querySelector('#loading-overlay').hidden,id,{timeout:60000});
const snapshot=async name=>page.screenshot({path:path.join(evidence,name+'.png'),fullPage:true});
const installPreview=async(id,recording)=>{
  const preview=structuredClone(recording);
  Object.assign(preview.metadata,{mode:'simulation',incomplete:true,recording_complete:false,duration_s:.02});
  delete preview.metadata.termination_reason;
  preview.frames=preview.frames.slice(0,1);preview.events=[];
  if(preview.perception?.frames)preview.perception.frames=preview.perception.frames.slice(0,1);
  await page.route(`${base}/api/session?id=${id}`,route=>route.fulfill({json:preview}),{times:1});
};
try {
  const completedJob=await get(`/api/jobs?id=${completedId}`),complete=await get(`/api/session?id=${completedId}`);
  const failedJob=await get(`/api/jobs?id=${failedId}`),failure=await get(`/api/session?id=${failedId}`);
  assert.equal(completedJob.status,'completed');assert.equal(complete.metadata.recording_complete,true);
  assert.equal(failedJob.status,'failed');assert.equal(failure.metadata.incomplete,true);
  await installPreview(completedId,complete);
  await page.goto(`${base}/?session=${completedId}&panel=health&map=1&pin=lidar_filtered&camera=follow`);await ready(completedId);
  assert.equal(await page.locator('#recording-warning').isVisible(),false);
  await page.evaluate(latest=>window.__studio.appendLiveFrame(latest),{...completedJob.latest,runtime:completedJob.runtime});
  assert.equal(await page.evaluate(()=>window.__studio.state.session.metadata.mode),'simulation');
  assert.equal(await page.evaluate(()=>window.__studio.state.session.frames.length),2);
  assert.equal(await page.locator('#recording-warning').isVisible(),false);
  assert.equal(await page.locator('#playback-state').textContent(),'CPU RUN · COMPLETED');
  assert.match(await page.locator('#source-badge').textContent(),/FINAL LIVE SAMPLE/);
  checks.push('A real completed worker snapshot remains a bounded simulation preview without a false failure banner.');
  await page.click('#workspace-test');await page.waitForSelector('#job-picker');
  await page.waitForFunction(id=>window.__workbench.state.jobs?.some(job=>job.id===id),completedId);
  await page.selectOption('#job-picker',completedId);await page.waitForSelector('#open-job-replay');
  let responseStarted,releaseResponse;
  const started=new Promise(resolve=>responseStarted=resolve),released=new Promise(resolve=>releaseResponse=resolve);
  await page.route(`${base}/api/session?id=${completedId}`,async route=>{const response=await route.fetch();responseStarted();await released;await route.fulfill({response});},{times:1});
  await page.click('#open-job-replay');await started;
  const pending=await page.evaluate(()=>({loading:window.__studio.state.loading,mode:window.__studio.state.session.metadata.mode,count:window.__studio.state.session.frames.length,time:window.__studio.state.time}));
  assert.equal(pending.loading,true);assert.equal(pending.mode,'simulation');assert.equal(pending.count,2);
  await page.evaluate(latest=>window.__studio.appendLiveFrame(latest),failedJob.latest);
  assert.deepEqual(await page.evaluate(()=>({count:window.__studio.state.session.frames.length,time:window.__studio.state.time})),{count:pending.count,time:pending.time});
  releaseResponse();await ready(completedId);
  await page.waitForFunction(()=>window.__workbench.state.workspace==='replay');
  assert.equal(await page.evaluate(()=>window.__studio.state.session.frames.length),complete.frames.length);
  assert.equal(await page.evaluate(()=>window.__studio.state.session.metadata.mode),'replay');
  assert.equal(await page.locator('#recording-warning').isVisible(),false);
  checks.push('Open recorded result waits for the actual full recording; delayed live packets cannot mutate the pending session.');
  await page.evaluate(()=>window.__studio.seek(4.8));
  await page.waitForFunction(()=>window.__workbench.state.sensors?.cursor_s===4.8);
  const before=await page.evaluate(()=>({count:window.__studio.state.session.frames.length,time:window.__studio.state.time,complete:window.__studio.state.session.metadata.recording_complete}));
  await page.evaluate(latest=>window.__studio.appendLiveFrame(latest),failedJob.latest);
  assert.deepEqual(await page.evaluate(()=>({count:window.__studio.state.session.frames.length,time:window.__studio.state.time,complete:window.__studio.state.session.metadata.recording_complete})),before);
  assert.equal(await page.locator('#recording-warning').isVisible(),false);
  await snapshot('full-completed-replay-lidar-map-health');
  checks.push('An opened complete replay keeps all source frames and cursor even if an old failed snapshot arrives.');
  await page.evaluate(()=>window.__studio.seek(4.82));
  await page.waitForFunction(()=>window.__workbench.state.sensors?.cursor_s===4.82);
  checks.push('A paused one-frame forward seek refreshes sensor cursor and age without waiting for playback.');
  await installPreview(failedId,failure);await page.evaluate(id=>{document.querySelector('#session-picker').value=id;return window.__studio.loadSession(id);},failedId);await ready(failedId);
  await page.evaluate(latest=>window.__studio.appendLiveFrame(latest),{...failedJob.latest,runtime:failedJob.runtime});
  assert.equal(await page.locator('#recording-warning').isVisible(),true);
  assert.ok((await page.locator('#recording-warning').textContent()).includes(failedJob.latest.metadata.termination_reason));
  assert.match(await page.locator('#recording-warning').textContent(),/WORKER FAILED/);
  assert.equal(await page.evaluate(()=>window.__studio.state.session.metadata.mode),'simulation');
  assert.equal(await page.locator('#playback-state').textContent(),'CPU RUN · FAILED');
  await snapshot('failed-live-preview-source-error');
  checks.push('An actual failed terminal snapshot immediately exposes its exact source error without claiming the preview is full replay.');
  await page.evaluate(id=>window.__studio.loadSession(id),failedId);await ready(failedId);
  assert.equal(await page.evaluate(()=>window.__studio.state.session.frames.length),failure.frames.length);
  assert.equal(await page.locator('#recording-warning').isVisible(),true);
  assert.match(await page.locator('#recording-warning').textContent(),/INCOMPLETE RECORDING/);
  assert.ok((await page.locator('#recording-warning').textContent()).includes(failedJob.latest.metadata.termination_reason));
  await page.evaluate(()=>window.__studio.seek(4.8));await page.waitForFunction(()=>window.__workbench.state.sensors?.cursor_s===4.8);
  await snapshot('full-failed-replay-lidar-map-health');
  checks.push('Opening the actual failed recording retains all executed frames and the source failure warning.');
  assert.deepEqual(errors,[]);
  const report={base,completed_id:completedId,failed_id:failedId,complete_frames:complete.frames.length,failed_frames:failure.frames.length,fixture:'Browser response delay and one-frame live preview envelope only; actual recorded values and errors',checks,errors};
  await writeFile(path.join(evidence,'replay-transition.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
}catch(error){await snapshot('transition-failure');throw error;}finally{await browser.close();}
